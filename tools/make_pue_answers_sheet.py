def setup(doc):
    s = doc.sections[0]
    s.page_width, s.page_height = Cm(21), Cm(29.7)
    s.left_margin = s.right_margin = Cm(1.4)
    s.top_margin = Cm(1.1)
    s.bottom_margin = Cm(1.0)
    normal = doc.styles["Normal"]
    rpr = normal.element.get_or_add_rPr()
    rf = rpr.find(qn("w:rFonts"))
    if rf is None:
        rf = OxmlElement("w:rFonts")
        rpr.insert(0, rf)
    for a in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rf.set(qn(a), FONT)
    normal.font.name = FONT
    normal.font.size = Pt(9)
    normal.paragraph_format.space_after = Pt(0.5)
    normal.paragraph_format.line_spacing = 1.0


def para(doc, text, size=9, bold=False, italic=False, align=None, after=0.5, before=0):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.line_spacing = 1.0
    r = p.add_run(text)
    r.font.name = FONT
    r.font.size = Pt(size)
    r.bold = bold
    r.italic = italic


def build():
    doc = Document()
    setup(doc)

    para(doc, "Ответы и ход решения", size=13, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, after=1)
    para(doc, "Лист для преподавателя · как каждый ответ выводится из листа 1", size=8.5, italic=True,
         align=WD_ALIGN_PARAGRAPH.CENTER, after=4)

    para(doc, "Формат: «Ответ» — что должно быть в работе; «Откуда» — какая норма листа 1 даёт этот ответ.",
         size=8.5, italic=True, after=5)

    for q, a, src in ITEMS:
        para(doc, q, size=9, bold=True, before=2, after=0.5)
        para(doc, "Ответ. " + a, size=9, after=0.5)
        para(doc, "Откуда: " + src, size=8, italic=True, after=2)

    os.makedirs(BASE, exist_ok=True)
    doc.save(OUT)
    print("saved:", OUT)


if __name__ == "__main__":
    build()
