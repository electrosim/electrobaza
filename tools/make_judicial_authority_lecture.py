def esc(text):
    return html_lib.escape(text, quote=False)


html_parts = []
section_open = False
for kind, value in BLOCKS:
    if kind == "title":
        continue
    if kind == "heading":
        if section_open:
            html_parts.append("</section>")
        html_parts.append("<section>")
        html_parts.append(f"  <h2>{esc(value)}</h2>")
        section_open = True
    elif kind == "body":
        if not section_open:
            html_parts.append("<section>")
            section_open = True
        html_parts.append(f"  <p>{esc(value)}</p>")
    elif kind == "lead":
        if not section_open:
            html_parts.append("<section>")
            section_open = True
        term, text = value
        html_parts.append(f"  <p><strong>{esc(term)}.</strong> {esc(text)}</p>")
